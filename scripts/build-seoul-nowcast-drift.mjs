import fs from 'node:fs/promises';
import crypto from 'node:crypto';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

// Builds the nowcast's seasonal drift table from IEM RKSI METARs (see
// fetch-iem-rksi-metars.mjs): the mean whole-degree change between reports 30
// minutes apart, for each KST half-hour slot and day of year, pooled over a
// ±15-day window. Reports on or after the cutoff date are excluded so a later
// test period stays out of training. No requests are made.
const [iemDir, cutoffDate, version, moduleOut, evidenceOut] = process.argv.slice(2);
if (!iemDir || !/^\d{4}-\d{2}-\d{2}$/.test(cutoffDate ?? '') || !/^rksi15l-iem-drift-v\d+$/.test(version ?? '') || !moduleOut || !evidenceOut) {
  throw new Error('Usage: node scripts/build-seoul-nowcast-drift.mjs <iem-dir> <cutoff-date-exclusive> <rksi15l-iem-drift-vN> <out-module.js> <new-evidence.json>');
}
const minute = 60_000, day = 24 * 60 * minute, windowDays = 15, slots = 48;
const sha256 = bytes => crypto.createHash('sha256').update(bytes).digest('hex');
const files = (await fs.readdir(iemDir)).filter(name => /^rksi-\d{4}\.csv$/.test(name)).sort();
if (!files.length) throw new Error('No rksi-YYYY.csv files found.');

const inputs = [];
const reports = new Map(); // KST wall-clock minute (as UTC milliseconds) -> temperature
for (const file of files) {
  const bytes = await fs.readFile(path.join(iemDir, file));
  inputs.push({ file, bytes: bytes.length, sha256: sha256(bytes) });
  const lines = bytes.toString('utf8').split(/\r?\n/);
  if (!lines[0].startsWith('station,valid,tmpc,')) throw new Error(`Unexpected header in ${file}.`);
  for (const line of lines.slice(1)) {
    const [station, valid, tmpc] = line.split(',');
    const match = /^(\d{4})-(\d{2})-(\d{2}) (\d{2}):(00|30)$/.exec(valid ?? '');
    const temperature = Number(tmpc);
    if (station !== 'RKSI' || !match || tmpc === 'M' || !Number.isFinite(temperature) || valid.slice(0, 10) >= cutoffDate) continue;
    const [, year, month, date, hour, minutes] = match.map(Number);
    reports.set(Date.UTC(year, month - 1, date, hour, minutes), temperature); // A later duplicate wins.
  }
}

const sums = new Float64Array(367 * slots), counts = new Float64Array(367 * slots);
let pairs = 0;
for (const [wall, temperature] of reports) {
  const later = reports.get(wall + 30 * minute);
  if (later === undefined) continue;
  const time = new Date(wall);
  const dayOfYear = 1 + Math.floor((Date.UTC(time.getUTCFullYear(), time.getUTCMonth(), time.getUTCDate()) - Date.UTC(time.getUTCFullYear(), 0, 1)) / day);
  const cell = dayOfYear * slots + time.getUTCHours() * 2 + time.getUTCMinutes() / 30;
  sums[cell] += later - temperature;
  counts[cell] += 1;
  pairs += 1;
}

const rows = [];
let minimumPairs = Infinity, maximumPairs = 0;
for (let center = 1; center <= 366; center += 1) {
  const row = [];
  for (let slot = 0; slot < slots; slot += 1) {
    let sum = 0, count = 0;
    for (let offset = -windowDays; offset <= windowDays; offset += 1) {
      const dayOfYear = ((center - 1 + offset) % 366 + 366) % 366 + 1;
      sum += sums[dayOfYear * slots + slot];
      count += counts[dayOfYear * slots + slot];
    }
    if (!count) throw new Error(`No report pairs for day ${center}, slot ${slot}.`);
    minimumPairs = Math.min(minimumPairs, count);
    maximumPairs = Math.max(maximumPairs, count);
    row.push(Math.round(1000 * sum / count));
  }
  rows.push(row);
}

const firstReport = new Date([...reports.keys()].reduce((a, b) => Math.min(a, b))).toISOString().slice(0, 16).replace('T', ' ');
const moduleText = `// Generated by scripts/build-seoul-nowcast-drift.mjs from open Iowa Environmental
// Mesonet RKSI METARs. Do not edit by hand: regenerate it and save new evidence.
export const NOWCAST_DRIFT_VERSION = ${JSON.stringify(version)};
export const NOWCAST_DRIFT_SOURCE = Object.freeze({
  archive: "Iowa Environmental Mesonet ASOS/METAR archive, station RKSI",
  reportsFrom: ${JSON.stringify(`${firstReport} KST`)},
  reportsBefore: ${JSON.stringify(`${cutoffDate} 00:00 KST`)},
  reportPairs: ${pairs},
  windowDays: ${windowDays},
  units: "mean 30-minute change, thousandths of a degree C",
});
// Rows are KST day of year 1-366; columns are half-hour slots from 00:00 to 23:30 KST.
export const NOWCAST_DRIFT_MILLI_C_PER_30_MIN = Object.freeze([
${rows.map(row => `  [${row.join(', ')}],`).join('\n')}
].map(Object.freeze));
`;
await fs.writeFile(moduleOut, moduleText);
const evidence = {
  generatedAt: new Date().toISOString(), version, cutoffDateExclusive: cutoffDate, windowDays,
  reports: reports.size, reportPairs: pairs, pairsPerCell: { minimum: minimumPairs, maximum: maximumPairs },
  inputs, moduleSha256: sha256(Buffer.from(moduleText)),
  scriptSha256: sha256(await fs.readFile(fileURLToPath(import.meta.url))),
};
await fs.writeFile(evidenceOut, `${JSON.stringify(evidence, null, 2)}\n`, { flag: 'wx' });
console.log(`${reports.size} reports, ${pairs} pairs, ${minimumPairs}-${maximumPairs} pairs per cell; wrote ${moduleOut}`);
