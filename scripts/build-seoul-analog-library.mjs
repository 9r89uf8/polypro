import fs from 'node:fs/promises';
import crypto from 'node:crypto';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { ANALOG_PEAK_CHECKPOINTS, checkpointFeatures, daySummary, parseRoutineMetar } from '../convex/lib/seoulAnalogPeakModel.js';

// Builds the analog peak library from IEM RKSI METARs (see
// fetch-iem-rksi-metars.mjs): for every KST day with enough routine reports,
// its whole-degree maximum, the first and last slots reaching it, and the
// checkpoint features, all parsed from the raw METAR text exactly as the live
// issuer parses stored reports. Reports on or after the cutoff are excluded.
const [iemDir, cutoffDate, version, moduleOut, evidenceOut] = process.argv.slice(2);
if (!iemDir || !/^\d{4}-\d{2}-\d{2}$/.test(cutoffDate ?? '') || !/^rksi-iem-analog-library-v\d+$/.test(version ?? '') || !moduleOut || !evidenceOut) {
  throw new Error('Usage: node scripts/build-seoul-analog-library.mjs <iem-dir> <cutoff-date-exclusive> <rksi-iem-analog-library-vN> <out-module.js> <new-evidence.json>');
}
const sha256 = bytes => crypto.createHash('sha256').update(bytes).digest('hex');
const files = (await fs.readdir(iemDir)).filter(name => /^rksi-\d{4}\.csv$/.test(name)).sort();
if (!files.length) throw new Error('No rksi-YYYY.csv files found.');

const inputs = [];
const days = new Map(); // KST date -> Map(slot -> parsed report)
let unparsed = 0;
for (const file of files) {
  const bytes = await fs.readFile(path.join(iemDir, file));
  inputs.push({ file, bytes: bytes.length, sha256: sha256(bytes) });
  const [header, ...lines] = bytes.toString('utf8').split(/\r?\n/);
  const columns = header.split(',');
  const validIndex = columns.indexOf('valid'), metarIndex = columns.indexOf('metar');
  if (validIndex < 0 || metarIndex !== columns.length - 1) throw new Error(`Unexpected header in ${file}.`);
  for (const line of lines) {
    const cells = line.split(',');
    const match = /^(\d{4}-\d{2}-\d{2}) (\d{2}):(00|30)$/.exec(cells[validIndex] ?? '');
    if (cells[0] !== 'RKSI' || !match || match[1] >= cutoffDate) continue;
    const report = parseRoutineMetar(cells.slice(metarIndex).join(','));
    if (!report) { unparsed += 1; continue; }
    if (!days.has(match[1])) days.set(match[1], new Map());
    days.get(match[1]).set(Number(match[2]) * 2 + Number(match[3]) / 30, report); // A later duplicate wins.
  }
}

const library = { dates: [], maxC: [], peakFirstSlot: [], peakLastSlot: [], checkpoints: {} };
for (const name of Object.keys(ANALOG_PEAK_CHECKPOINTS)) library.checkpoints[name] = { tempC: [], maxSoFarC: [], vectors: [] };
const round = value => Math.round(value * 10) / 10;
for (const date of [...days.keys()].sort()) {
  const reports = days.get(date);
  const summary = daySummary(reports);
  if (!summary) continue;
  library.dates.push(date);
  library.maxC.push(summary.maxC);
  library.peakFirstSlot.push(summary.peakFirstSlot);
  library.peakLastSlot.push(summary.peakLastSlot);
  for (const [name, slot] of Object.entries(ANALOG_PEAK_CHECKPOINTS)) {
    const features = checkpointFeatures(reports, slot);
    library.checkpoints[name].tempC.push(features ? features.tempC : null);
    library.checkpoints[name].maxSoFarC.push(features ? features.maxSoFarC : null);
    library.checkpoints[name].vectors.push(features ? features.vector.map(round) : null);
  }
}

const list = (values, indent, perLine = 20) => {
  const lines = [];
  for (let start = 0; start < values.length; start += perLine) {
    lines.push(`${indent}  ${values.slice(start, start + perLine).map(value => JSON.stringify(value)).join(', ')},`);
  }
  return `[\n${lines.join('\n')}\n${indent}]`;
};
const checkpointText = Object.entries(library.checkpoints).map(([name, data]) => `    ${JSON.stringify(name)}: {
      tempC: ${list(data.tempC, '      ')},
      maxSoFarC: ${list(data.maxSoFarC, '      ')},
      vectors: ${list(data.vectors, '      ', 1)},
    },`).join('\n');
const moduleText = `// Generated by scripts/build-seoul-analog-library.mjs from open Iowa Environmental
// Mesonet RKSI METARs. Do not edit by hand: regenerate it and save new evidence.
// Peak slots and checkpoint features follow convex/lib/seoulAnalogPeakModel.js.
export const ANALOG_LIBRARY_VERSION = ${JSON.stringify(version)};
export const ANALOG_LIBRARY_SOURCE = Object.freeze({
  archive: "Iowa Environmental Mesonet ASOS/METAR archive, station RKSI",
  daysFrom: ${JSON.stringify(library.dates[0])},
  reportsBefore: ${JSON.stringify(`${cutoffDate} 00:00 KST`)},
  days: ${library.dates.length},
  slots: "KST half hours: 0 is 00:00 and 47 is 23:30",
});
export const ANALOG_LIBRARY = Object.freeze({
  dates: ${list(library.dates, '  ', 8)},
  maxC: ${list(library.maxC, '  ')},
  peakFirstSlot: ${list(library.peakFirstSlot, '  ')},
  peakLastSlot: ${list(library.peakLastSlot, '  ')},
  checkpoints: {
${checkpointText}
  },
});
`;
await fs.writeFile(moduleOut, moduleText);
const evidence = {
  generatedAt: new Date().toISOString(), version, cutoffDateExclusive: cutoffDate,
  daysWithReports: days.size, daysKept: library.dates.length, unparsedReports: unparsed,
  checkpointDays: Object.fromEntries(Object.entries(library.checkpoints).map(([name, data]) => [name, data.vectors.filter(Boolean).length])),
  inputs, moduleSha256: sha256(Buffer.from(moduleText)),
  scriptSha256: sha256(await fs.readFile(fileURLToPath(import.meta.url))),
};
await fs.writeFile(evidenceOut, `${JSON.stringify(evidence, null, 2)}\n`, { flag: 'wx' });
console.log(`${library.dates.length} of ${days.size} days kept; checkpoint days ${JSON.stringify(evidence.checkpointDays)}; ${unparsed} unparsed reports; wrote ${moduleOut}`);
