const NOMINAL = Date.parse("2026-10-30T02:00:00Z"), MJD_EPOCH = Date.UTC(1858, 10, 17);
const COMMON = { errorCount: 65535, outsideScanCount: 65534, speedOfLight: 299792458,
  planckConstant: 6.62606957e-34, boltzmannConstant: 1.3806488e-23 };
const B07 = { ...COMMON, wavelengthMicrometers: 3.8289, validBits: 14,
  gain: -0.000739381908147643, offset: 12.088894198221782,
  c0: -0.462794497192785, c1: 1.00143263846873, c2: -9.01426428759167e-7,
  C0: 0.46215799104457, C1: 0.998569919085378, C2: 8.98849935615215e-7 };
const B13 = { ...COMMON, wavelengthMicrometers: 10.4074, validBits: 12,
  gain: -0.0037525074318633814, offset: 15.197657722429469,
  c0: -0.118260812197365, c1: 1.00101143081895, c2: -1.80800453227613e-6,
  C0: 0.118211645089097, C1: 0.998989021775474, C2: 1.80702978762378e-6 };
const B04 = { ...COMMON, wavelengthMicrometers: .85668, validBits: 11,
  gain: .1819594117647059, offset: -3.639188235294118,
  albedoCoefficient: .00323278300590629, updatedGain: .18714005, updatedOffset: -3.74280096 };

function fixture(nominalTimeUtc = NOMINAL) {
  return [4, 7, 13].map(band => {
    const scale = band === 4 ? 2 : 1, columns = 1500 * scale, lines = 1200 * scale;
    const calibration = { ...({ 4: B04, 7: B07, 13: B13 }[band]) };
    const count = band === 4 ? 600 : band === 7 ? Math.round((1 - B07.offset) / B07.gain)
      : Math.round((himawariBandRadianceAtTemperature(285, B13) - B13.offset) / B13.gain);
    const bytes = Buffer.alloc(columns * lines * 2), pattern = Buffer.alloc(2); pattern.writeUInt16LE(count); bytes.fill(pattern);
    const start = (nominalTimeUtc + 15_000 - MJD_EPOCH) / 86_400_000;
    return { key: `fixture-B${String(band).padStart(2, "0")}`, band, nominalTimeUtc, area: "JP01", columns, lines,
      bytes, little: true, headerLength: 0, calibration,
      projection: { subLon: 140.7, cfac: 20466275 * scale, lfac: 20466275 * scale,
        coff: 1075 * scale + .5, loff: 2300 * scale + .5, rsKm: 42164, aKm: 6378.137, bKm: 6356.7523 },
      lineTimes: [{ line: 1, mjd: start }, { line: lines, mjd: start + 96_000 / 86_400_000 }] };
  });
}

test("published JMA ranges use inverse gamma and warm temperatures increase blue", () => {
  assert.deepEqual(himawariMicrophysicsRgb(0, .02, 203.5), [0, 0, 0]);
  assert.deepEqual(himawariMicrophysicsRgb(1.02, .82, 303.2), [255, 255, 255]);
  assert.deepEqual(himawariMicrophysicsRgb(1.02 * .5 ** .95, .02 + .8 * .5 ** 2.6, 253.35), [128, 128, 128]);
  assert.equal(himawariMicrophysicsRgb(.5, .2, 220)[2], 42);
  assert.equal(himawariMicrophysicsRgb(.5, .2, 290)[2], 221);
  assert.deepEqual(himawariMicrophysicsRgb(-.1, -.1, 180), [0, 0, 0]);
  assert.equal(himawariMicrophysicsRgb(.5, NaN, 280), null);
});

test("B07 inverse HSD Planck calibration agrees with independently integrated official H09 SRF", () => {
  // These are independent Python/NumPy Planck integrations over all 3557
  // wavelengths in JMA's official H09 SRF, not values generated by this helper.
  const reference = [[200, .0010221569287679087], [230, .011769249330320133],
    [250, .04335112211521808], [270, .13167614789742985], [290, .3432166490205016],
    [310, .7907254855657772], [330, 1.6466921574462987]];
  for (const [temperature, radiance] of reference) {
    const actual = himawariBandRadianceAtTemperature(temperature, B07);
    assert.ok(Math.abs(actual / radiance - 1) < 2.1e-5, `SRF comparison at ${temperature} K`);
  }
  assert.equal(himawariBandRadianceAtTemperature(149, B07), null);
  assert.equal(himawariBandRadianceAtTemperature(361, B07), null);
  assert.equal(himawariBandRadianceAtTemperature(280, { ...B07, C1: NaN }), null);
});

test("thermal/solar separation recovers physical mixtures including the emissivity denominator", () => {
  for (const time of [Date.parse("2026-01-03T00:00:00Z"), Date.parse("2026-07-04T00:00:00Z")]) {
    for (const temperature of [230, 270, 300]) {
      const thermal = himawariBandRadianceAtTemperature(temperature, B07);
      const distance = himawariEarthSunDistanceAu(time), cosine = .6;
      const solar = HIMAWARI9_B07_SOLAR.irradianceAtOneAu * cosine / (Math.PI * distance ** 2);
      for (const reflection of [0, .02, .2, .7, 1]) {
        const measured = reflection * solar + (1 - reflection) * thermal;
        assert.ok(Math.abs(himawariReflectedB07(measured, temperature, B07, cosine, time) - reflection) < 1e-12);
      }
    }
  }
  assert.ok(himawariEarthSunDistanceAu(Date.parse("2026-01-03T00:00:00Z")) < 1);
  assert.ok(himawariEarthSunDistanceAu(Date.parse("2026-07-04T00:00:00Z")) > 1);
});

test("clear and cloudy real-point reflectances agree with independent full-SRF thermal separation", () => {
  // Python HSD parsing/solar geometry plus numerical Planck integration across
  // JMA's entire B07 SRF. It does not call the JS inverse-Planck helper.
  const cases = [
    { radiance: .48947082320155744, temperature: 289.2385280137521, cosine: .5852268840867542,
      time: 1793325500083.078, reflectance: .09774651362108759 },
    { radiance: .3637758988164581, temperature: 258.573113661165, cosine: .5018256601764914,
      time: 1793235654713.470, reflectance: .1832584415648436 },
  ];
  for (const row of cases) {
    const result = himawariReflectedB07(row.radiance, row.temperature, B07, row.cosine, row.time);
    assert.ok(Math.abs(result - row.reflectance) < 2e-6);
  }
});

