test("coarse B07 sampling preserves native-cell colors and returns honest band clocks", () => {
  const hsds = fixture(), b07 = hsds[1];
  const pos = himawariNativePosition(b07.projection, 37.4602, 126.4407);
  const center = himawariNativeCenter(b07.projection, pos.row, pos.column);
  const a = sampleHimawariMicrophysicsPoint(hsds, center.latitude, center.longitude, NOMINAL);
  const b = sampleHimawariMicrophysicsPoint(hsds, center.latitude + .0001, center.longitude + .0001, NOMINAL);
  assert.deepEqual(a.rgb, b.rgb);
  assert.deepEqual(a.samples, b.samples);
  const image = renderHimawariMicrophysics(hsds, { nominalTimeUtc: NOMINAL });
  assert.equal(image.status, "ok"); assert.equal(image.validFraction, 1);
  assert.equal(image.geometry.nominalResolutionKm, 2);
  assert.ok(image.geometry.nativePixelSpacingKm.row > 2.8);
  assert.ok(image.diagnostics.nativePixelsSampled < 2000);
  assert.equal(image.observedAt, Math.max(...image.sourceObservations.map(source => source.observedAt)));
  assert.deepEqual(image.sourceObservations.map(source => source.band), ["B04", "B07", "B13"]);
  assert.equal(image.display.recipe, "jma-day-microphysics-warm-v1");
  assert.ok(image.display.legend.every(item => /^#[0-9a-f]{6}$/i.test(item.color) && item.label.length <= 100));
  assert.equal(image.display.interpretationOnly, true);
});

test("incomplete, duplicate, mixed-slot or unsynchronized band bundles cannot render", () => {
  const hsds = fixture();
  assert.throws(() => renderHimawariMicrophysics(hsds.slice(0, 2), { nominalTimeUtc: NOMINAL }), /complete three-band/);
  assert.throws(() => renderHimawariMicrophysics([hsds[0], hsds[1], hsds[1]], { nominalTimeUtc: NOMINAL }), /duplicate/);
  hsds[2].nominalTimeUtc += 150_000;
  assert.throws(() => renderHimawariMicrophysics(hsds, { nominalTimeUtc: NOMINAL }), /mismatched band slot/);
  hsds[2].nominalTimeUtc = NOMINAL;
  hsds[2].lineTimes = hsds[2].lineTimes.map(row => ({ ...row, mjd: row.mjd + 61_000 / 86_400_000 }));
  assert.throws(() => renderHimawariMicrophysics(hsds, { nominalTimeUtc: NOMINAL }), /60 seconds/);
  assert.throws(() => decodeHimawariMicrophysics([], { nominalTimeUtc: NOMINAL }), /complete three-band/);
});

test("night produces no image and missing source cells appear as a distinct checker mask", () => {
  const night = Date.parse("2026-10-30T14:00:00Z");
  const unavailable = renderHimawariMicrophysics(fixture(night), { nominalTimeUtc: night });
  assert.equal(unavailable.status, "unavailable"); assert.equal(unavailable.rgba, undefined);
  assert.match(unavailable.reason, /10 degrees/);
  const hsds = fixture(), b07 = hsds[1], pos = himawariNativePosition(b07.projection, 37.4602, 126.4407);
  b07.bytes.writeUInt16LE(65535, 2 * (pos.row * b07.columns + pos.column));
  const image = renderHimawariMicrophysics(hsds, { nominalTimeUtc: NOMINAL });
  assert.equal(image.status, "ok"); assert.ok(image.validFraction < 1 && image.validFraction > .99);
  assert.ok(image.diagnostics.rejected.source_pixel > 0);
  let marked = 0;
  for (let i = 0; i < image.rgba.length; i += 4) {
    const red = image.rgba[i];
    if ([36, 90].includes(red) && image.rgba[i + 1] === red && image.rgba[i + 2] === red) marked++;
  }
  assert.equal(marked, image.diagnostics.rejected.source_pixel);
  b07.bytes.fill(255);
  assert.equal(renderHimawariMicrophysics(hsds, { nominalTimeUtc: NOMINAL }).status, "unavailable");
});

const REAL_FILES = [
  ["B04", "10", "453b4168d23170c5fcef6e3d6fedd16b1d69938e3bc455a2094e315422f1eb93"],
  ["B07", "20", "329f79bc7aa550bc72b5fa9c5fe8d948bd2ed6c5e4c50def48e565c436e4636c"],
  ["B13", "20", "a9d4a6b41c816384fec7b8b5ac7e118c82310c55c2ccd53e07aba66672506f49"],
].map(([band, resolution, sha256]) => {
  const name = `HS_H09_20261030_0150_${band}_JP04_R${resolution}_S0101.DAT.bz2`;
  return { band, sha256, key: `AHI-L1b-Japan/2026/10/30/0150/${name}`, path: new URL(`../tmp/seoul-microphysics/${name}`, import.meta.url) };
});

test("retained real H09 bundle decodes to lossless RGB with complete source timing", {
  skip: !REAL_FILES.every(file => existsSync(file.path)), timeout: 120_000,
}, () => {
  const nominalTimeUtc = Date.parse("2026-10-30T01:57:30Z");
  const inputs = REAL_FILES.map(file => {
    const bytes = readFileSync(file.path);
    assert.equal(createHash("sha256").update(bytes).digest("hex"), file.sha256);
    return { key: file.key, bytes, nominalTimeUtc };
  });
  const result = decodeHimawariMicrophysics(inputs, { nominalTimeUtc });
  assert.equal(result.status, "ok"); assert.equal(result.validFraction, 1);
  assert.equal(result.version, "rksi-himawari-microphysics-v1");
  assert.equal(result.contentType, "image/png");
  const image = PNG.sync.read(result.imageBytes);
  assert.equal(image.width, 256); assert.equal(image.height, 256);
  assert.ok(image.data.some((value, i) => i % 4 === 0 && value !== image.data[i + 1]));
  // Independently calculated Python/full-SRF color for the airport native cell.
  assert.deepEqual([...image.data.subarray(4 * (128 * 256 + 128), 4 * (128 * 256 + 128) + 4)], [69, 104, 219, 255]);
  assert.deepEqual(result.sourceObservations.map(source => source.observedAt), [1793325499672, 1793325500083, 1793325500710]);
  assert.equal(result.observedAt, 1793325500710);
  const missing = inputs.map(row => ({ ...row })); missing[2].nominalTimeUtc += 150_000;
  assert.throws(() => decodeHimawariMicrophysics(missing, { nominalTimeUtc }), /mismatched input band/);
});
